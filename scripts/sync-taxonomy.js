// Regenerates backend/taxonomy.js (the lists the API validates against) from the
// GENRES and TW_TAGS lists in frontend/src/components/ui.jsx.
// Run after editing those lists:   node scripts/sync-taxonomy.js
const fs   = require("fs");
const path = require("path");

const ui  = fs.readFileSync(path.join(__dirname, "../frontend/src/components/ui.jsx"), "utf8");
const get = (name) => {
  const m = ui.match(new RegExp(`export const ${name} = \\[([\\s\\S]*?)\\n\\];`));
  if (!m) throw new Error(`Couldn't find ${name} in ui.jsx`);
  return [...m[1].matchAll(/"((?:[^"\\]|\\.)*)"/g)].map(x => JSON.parse(`"${x[1]}"`));
};

const out =
`// GENERATED by scripts/sync-taxonomy.js from frontend/src/components/ui.jsx — don't edit by hand.
// The API only accepts these genres / trigger warnings (plus any a book already has).
module.exports = {
  GENRES: ${JSON.stringify(get("GENRES"), null, 2)},
  TW_TAGS: ${JSON.stringify(get("TW_TAGS"), null, 2)},
};
`;
fs.writeFileSync(path.join(__dirname, "../backend/taxonomy.js"), out);
console.log("Wrote backend/taxonomy.js");
